// Seeded ops users: the owner (full runs) and the demo duty manager (judges, Quick runs).

import { randomBytes } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import bcrypt from "bcryptjs";
import type { PrismaClient } from "@/generated/prisma/client";

export const DEFAULT_DEMO_EMAIL = "duty.manager@demo.groundside.test";

export function hashPassword(password: string): Promise<string> {
  return bcrypt.hash(password, 10);
}

export function verifyPassword(password: string, hash: string): Promise<boolean> {
  return bcrypt.compare(password, hash);
}

/**
 * Creates or updates the users from env vars. If DEMO_OPS_PASSWORD is not set, a random one
 * is generated and written to scripts/out/demo-credentials.txt (git-ignored), never printed.
 */
export async function seedUsers(db: PrismaClient, env: Record<string, string | undefined> = process.env) {
  const out: string[] = [];
  const upsert = async (email: string, name: string, password: string) => {
    const passwordHash = await hashPassword(password);
    await db.user.upsert({ where: { email }, create: { email, name, passwordHash, role: "DUTY_MANAGER" }, update: { name, passwordHash } });
  };
  if (env.OWNER_EMAIL && env.OWNER_PASSWORD) {
    await upsert(env.OWNER_EMAIL, "Owner", env.OWNER_PASSWORD);
    out.push(`owner: ${env.OWNER_EMAIL} (password from OWNER_PASSWORD)`);
  }
  const demoEmail = env.DEMO_OPS_EMAIL || DEFAULT_DEMO_EMAIL;
  let demoPassword = env.DEMO_OPS_PASSWORD;
  let generated = false;
  if (!demoPassword) {
    demoPassword = randomBytes(12).toString("base64url");
    generated = true;
  }
  await upsert(demoEmail, "Demo Duty Manager", demoPassword);
  if (generated) {
    const dir = path.join(process.cwd(), "scripts", "out");
    mkdirSync(dir, { recursive: true });
    writeFileSync(path.join(dir, "demo-credentials.txt"), `Demo duty manager (local only, generated by npm run seed)\nemail: ${demoEmail}\npassword: ${demoPassword}\n`);
    out.push(`demo duty manager: ${demoEmail} (generated password in scripts/out/demo-credentials.txt)`);
  } else {
    out.push(`demo duty manager: ${demoEmail} (password from DEMO_OPS_PASSWORD)`);
  }
  return out;
}
