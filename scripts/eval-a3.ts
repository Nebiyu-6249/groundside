// npm run eval:a3
// Asks A3 for each notice outcome (scenario A flight) and writes docs/EVAL_A3.md with the text,
// whether it passed the code checks, and the cost. A notice that fails twice is reported as a
// fallback: the app would use its code template.

import { writeFileSync } from "node:fs";
import path from "node:path";
import { A3_PROMPT_VERSION, NOTICE_OUTCOMES, writeNotice } from "../src/lib/ai/a3/notice";
import { aiConfig } from "../src/lib/ai/config";
import { openAiCaller } from "../src/lib/ai/provider";
import { memorySpendLog } from "../src/lib/ai/spend";
import { loadRulePack } from "../src/lib/rules/pack";

const NOTICE_RULES = ["REG-5-1-A", "REG-5-1-B", "REG-5-3", "REG-6-1", "REG-7-1", "REG-8-1", "REG-9-1", "REG-14-2", "REG-15"];

async function main() {
  const config = aiConfig();
  if (!config.apiKey) throw new Error("OPENAI_API_KEY is not set");
  const spend = memorySpendLog();
  const rules = loadRulePack().filter((r) => NOTICE_RULES.includes(r.id)).map((r) => ({ id: r.id, title: r.title, summary: r.summary }));
  const sections: string[] = [];
  let passed = 0;
  for (const outcome of NOTICE_OUTCOMES) {
    const r = await writeNotice({ outcome, flight: { number: "DEMO 412", origin: "Frankfurt", destination: "Dubai", type: "CANCELLATION" }, rules }, { config, caller: openAiCaller(config.apiKey), spend });
    if (r) passed++;
    console.log(`${r ? "pass" : "FALLBACK"} ${outcome}${r ? ` (${r.retries} retries, citations ${r.citations.join(", ") || "none"})` : ""}`);
    sections.push(`## ${outcome}: ${r ? `passed the checks (${r.retries} retries)` : "failed twice; the code template would be used"}`, "", r ? "```text\n" + r.text + "\n```" : "", r ? `Citations: ${r.citations.join(", ") || "none"}` : "", "");
  }
  const cost = spend.calls.reduce((s, x) => s + x.costUsd, 0);
  writeFileSync(
    path.join(process.cwd(), "docs", "EVAL_A3.md"),
    [
      "# Eval report: A3 notice writer",
      "",
      `Generated by \`npm run eval:a3\` on ${new Date().toISOString()}. Model \`${config.models.A3}\`, prompt \`${A3_PROMPT_VERSION}\`.`,
      "",
      "Checks: required placeholders present, no other placeholders, no amounts of money in the text, citations from the rule list only, short sentences, at most about 160 words, and for a denial the national enforcement body. Code fills the placeholders per passenger.",
      "",
      `Result: ${passed} of ${NOTICE_OUTCOMES.length} outcomes passed. Cost: ${cost.toFixed(4)} USD.`,
      "",
      ...sections,
    ].join("\n"),
  );
  console.log(`${passed}/${NOTICE_OUTCOMES.length}, ${cost.toFixed(4)} USD`);
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err);
  process.exitCode = 1;
});
