// npm run eval:a4
// Runs A4 (passenger questions) on data/evals/a4-cases.json against the live model and writes
// docs/EVAL_A4.md. A fallback answer counts as validated: false. Costs well under one cent.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { A4_PROMPT_VERSION, answerQuestion, type CaseFile } from "../src/lib/ai/a4/answer";
import { aiConfig } from "../src/lib/ai/config";
import { openAiCaller } from "../src/lib/ai/provider";
import { memorySpendLog } from "../src/lib/ai/spend";
import { loadRulePack } from "../src/lib/rules/pack";
import { displayTitle } from "../src/lib/rules/display";

interface Case {
  id: string;
  caseFile: string;
  question: string;
  expect: { validated?: boolean; offerHuman?: boolean; category?: string[]; mentions?: string[]; notMentions?: string[] };
}

async function main() {
  const config = aiConfig();
  if (!config.apiKey) throw new Error("OPENAI_API_KEY is not set");
  const caller = openAiCaller(config.apiKey);
  const spend = memorySpendLog();
  const data = JSON.parse(readFileSync(path.join(process.cwd(), "data", "evals", "a4-cases.json"), "utf8")) as { caseFiles: Record<string, CaseFile>; cases: Case[] };
  const rules = loadRulePack().filter((r) => r.status === "VERIFIED" && r.kind !== "GUIDANCE").map((r) => ({ id: r.id, title: displayTitle(r), summary: r.summary }));
  const rows: string[] = [];
  let passed = 0;
  for (const c of data.cases) {
    const r = await answerQuestion(c.question, data.caseFiles[c.caseFile], rules, { config, caller, spend });
    const a = r.output.answer.toLowerCase();
    const fails: string[] = [];
    if (c.expect.validated !== undefined && r.validated !== c.expect.validated) fails.push(`validated ${r.validated}`);
    if (c.expect.offerHuman !== undefined && r.output.offerHuman !== c.expect.offerHuman) fails.push(`offerHuman ${r.output.offerHuman}`);
    if (c.expect.category && !c.expect.category.includes(r.output.category)) fails.push(`category ${r.output.category}`);
    for (const m of c.expect.mentions ?? []) if (!a.includes(m.toLowerCase())) fails.push(`does not mention "${m}"`);
    for (const m of c.expect.notMentions ?? []) if (a.includes(m.toLowerCase())) fails.push(`mentions "${m}"`);
    if (fails.length === 0) passed++;
    const answer = r.output.answer.replaceAll("|", "/").replaceAll("\n", " ");
    rows.push(`| ${c.id} | ${fails.length ? "fail" : "pass"} | ${r.output.category} | ${r.output.offerHuman ? "yes" : "no"} | ${r.validated ? "yes" : "fallback"} | ${r.retries} | ${answer} | ${fails.join("; ")} |`);
    console.log(`${fails.length ? "FAIL" : "pass"} ${c.id}${fails.length ? `: ${fails.join("; ")}` : ""}${r.errors.length ? ` [validator: ${r.errors.join("; ")}]` : ""}`);
  }
  const cost = spend.calls.reduce((s, x) => s + x.costUsd, 0);
  writeFileSync(
    path.join(process.cwd(), "docs", "EVAL_A4.md"),
    [
      "# Eval report: A4 passenger questions",
      "",
      `Generated by \`npm run eval:a4\` on ${new Date().toISOString()}. Model \`${config.models.A4}\`, prompt \`${A4_PROMPT_VERSION}\`. Cases in \`data/evals/a4-cases.json\` (synthetic case files).`,
      "",
      "Code checks every answer before it is shown: cited rules must be VERIFIED rule-pack IDs, every amount must appear in the case file, and legal-advice, dispute and human requests always offer a person. A failed check gets one retry, then a safe fallback.",
      "",
      `Result: ${passed} of ${data.cases.length} pass. Cost of this run: ${cost.toFixed(4)} USD (estimated from token counts).`,
      "",
      "| Case | Result | Category | Offers a person | Validated | Retries | Answer | Failed expectations |",
      "|---|---|---|---|---|---|---|---|",
      ...rows,
      "",
    ].join("\n"),
  );
  console.log(`${passed}/${data.cases.length} pass, ${cost.toFixed(4)} USD`);
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err);
  process.exitCode = 1;
});
