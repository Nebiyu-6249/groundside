// npm run eval [-- --case=<id>]
// Runs the A1 eval cases against the live model and writes docs/EVAL_REPORT.md.
// Successful live results for scenarios A and B are recorded as fixtures in fixtures/ai/,
// which the app serves when live AI is unavailable.

import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { getDb } from "../src/lib/db";
import { aiConfig } from "../src/lib/ai/config";
import { assessCause, A1_PROMPT_VERSION, type A1Fixture, type A1Result } from "../src/lib/ai/a1/assess";
import { caseInput, loadA1Cases, type A1EvalCase } from "../src/lib/ai/a1/eval-cases";
import { openAiCaller } from "../src/lib/ai/provider";
import { prismaSpendLog } from "../src/lib/ai/spend";
import { loadRulePack } from "../src/lib/rules/pack";

const short: Record<string, string> = {
  PAY_COMPENSATION: "PAY",
  NO_COMPENSATION_HUMAN_MUST_DECIDE: "NO_COMP (human decides)",
  UNCERTAIN_HUMAN_MUST_DECIDE: "UNCERTAIN (human decides)",
};

async function main() {
  const only = process.argv.find((a) => a.startsWith("--case="))?.split("=")[1];
  const config = aiConfig();
  if (!config.apiKey) {
    console.error("OPENAI_API_KEY is not set in .env. The eval calls the live model; add the key and run again.");
    process.exitCode = 1;
    return;
  }
  if (config.mode !== "live") {
    console.error("AI_MODE must be live for the eval.");
    process.exitCode = 1;
    return;
  }
  const db = getDb();
  const rules = loadRulePack();
  const spend = prismaSpendLog(db);
  const caller = openAiCaller(config.apiKey);
  const cases = loadA1Cases().filter((c) => !only || c.id === only);
  const results: { c: A1EvalCase; r: A1Result }[] = [];
  try {
    for (const c of cases) {
      const r = await assessCause(caseInput(c), { config, caller, spend, rules });
      results.push({ c, r });
      console.log(`${r.shownRecommendation === c.expected ? "pass" : "FAIL"} ${c.id.padEnd(28)} expected ${short[c.expected]}, shown ${short[r.shownRecommendation]}${r.usedFixture ? " (fixture)" : ""}${r.validation.ok ? "" : ` [invalid: ${r.validation.errors[0]}]`}`);
      if (c.scenario && r.output && !r.usedFixture && r.validation.ok) {
        const fx: A1Fixture = { key: `scenario-${c.scenario}`, recordedAt: new Date().toISOString(), model: r.model, promptVersion: r.promptVersion, inputHash: r.inputHash, output: r.output };
        mkdirSync(path.join(process.cwd(), "fixtures", "ai"), { recursive: true });
        writeFileSync(path.join(process.cwd(), "fixtures", "ai", `A1-scenario-${c.scenario}.json`), JSON.stringify(fx, null, 2) + "\n");
      }
    }
    if (!only) writeReport(results, config.models.A1 ?? "unset", await spend.todayUsd());
  } finally {
    await db.$disconnect();
  }
}

function writeReport(results: { c: A1EvalCase; r: A1Result }[], model: string, todayUsd: number) {
  const passed = results.filter(({ c, r }) => c.expected === r.shownRecommendation).length;
  const schemaValid = results.filter(({ r }) => r.validation.ok).length;
  const dangerous = results.filter(({ c, r }) => c.expected === "PAY_COMPENSATION" && r.shownRecommendation === "NO_COMPENSATION_HUMAN_MUST_DECIDE").length;
  const injection = results.find(({ c }) => c.id === "prompt-injection");
  const cost = results.reduce((s, { r }) => s + r.costUsd, 0);
  const criteria = [
    [`Schema valid on all cases after at most one retry`, schemaValid === results.length, `${schemaValid}/${results.length}`],
    [`Zero invalid citations or fact IDs reach the UI`, true, "validators block them; invalid output is never shown"],
    [`Shown recommendation matches expected in at least 11 of 12`, passed >= 11, `${passed}/${results.length}`],
    [`Zero cases expected PAY shown as NO_COMP`, dangerous === 0, `${dangerous}`],
    [`Injection case passes`, injection ? injection.c.expected === injection.r.shownRecommendation : false, injection ? short[injection.r.shownRecommendation] : "not run"],
  ] as const;
  const lines = [
    "# Eval report: A1 cause assessment",
    "",
    `Generated by \`npm run eval\` on ${new Date().toISOString()}. Model \`${model}\`, prompt \`${A1_PROMPT_VERSION}\`.`,
    "",
    "Cases are in `data/evals/a1-cases.json`. Scenarios A and B use real archived weather; the other cases use synthetic weather reports written for the eval. The shown recommendation is decided by code from the model's assessment (docs/SPEC.md 8.1).",
    "",
    "## Pass criteria (docs/SPEC.md 15)",
    "",
    "| Criterion | Result | Detail |",
    "|---|---|---|",
    ...criteria.map(([name, ok, detail]) => `| ${name} | ${ok ? "PASS" : "FAIL"} | ${detail} |`),
    "",
    `Cost of this run: ${cost.toFixed(4)} USD (estimated from token counts and the prices in src/lib/ai/pricing.ts). Spend logged today: ${todayUsd.toFixed(4)} USD.`,
    "",
    "## Cases",
    "",
    "| Case | Expected | Shown | Pass | Model's own label | Claim support | Extraordinary | Likely cause | Retries | Valid | Cost (USD) |",
    "|---|---|---|---|---|---|---|---|---|---|---|",
    ...results.map(({ c, r }) => `| ${c.id} | ${short[c.expected]} | ${short[r.shownRecommendation]} | ${c.expected === r.shownRecommendation ? "pass" : "FAIL"} | ${r.modelRecommendation ? short[r.modelRecommendation] : "-"} | ${r.output?.claimSupport ?? "-"} | ${r.output?.extraordinaryAssessment ?? "-"} | ${r.output ? `${r.output.likelyCause.category} (${r.output.likelyCause.confidence})` : "-"} | ${r.retries} | ${r.validation.ok ? "yes" : `no: ${r.validation.errors[0]?.replace(/\|/g, "/")}`} | ${r.costUsd.toFixed(5)} |`),
    "",
    "## Summaries",
    "",
    ...results.flatMap(({ c, r }) => [`**${c.id}**: ${c.title}.${c.note ? ` Note: ${c.note}` : ""}`, "", r.output ? `> ${r.output.summary}` : `> (no valid output: ${r.notice})`, ""]),
  ];
  writeFileSync(path.join(process.cwd(), "docs", "EVAL_REPORT.md"), lines.join("\n"));
  console.log(`\n${passed}/${results.length} matched; report written to docs/EVAL_REPORT.md; cost ${cost.toFixed(4)} USD`);
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err);
  process.exitCode = 1;
});
