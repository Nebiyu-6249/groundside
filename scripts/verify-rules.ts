// npm run rules:verify [-- --refresh]
// Checks every rule's excerpt word for word against the official text it cites, and writes
// docs/RULE_PACK_STATUS.md. Exits non-zero if a VERIFIED rule's excerpt is not found.

import { writeFileSync } from "node:fs";
import path from "node:path";
import { loadRulePack } from "../src/lib/rules/pack";
import { FRAGMENT_SEPARATOR, type Rule } from "../src/lib/rules/schema";
import { normalise, officialText } from "./lib/legal-text";

type Check = { rule: Rule; found: boolean | null; detail: string };

async function check(rule: Rule, refresh: boolean): Promise<Check> {
  if (rule.celex === null) return { rule, found: null, detail: "Demo Air policy; checked against data/policy" };
  const text = await officialText(rule.celex, { refresh });
  const missing = rule.excerpt
    .split(FRAGMENT_SEPARATOR)
    .map(normalise)
    .filter((fragment) => !text.includes(fragment));
  return missing.length === 0
    ? { rule, found: true, detail: "excerpt found verbatim" }
    : { rule, found: false, detail: `not found: "${missing[0].slice(0, 80)}..."` };
}

function statusTable(checks: Check[]): string {
  const rows = checks.map(({ rule, found }) => {
    const check = found === null ? "policy" : found ? "verbatim" : "MISMATCH";
    return `| ${rule.id} | ${rule.title.replace(/\|/g, "/")} | ${rule.kind} | ${rule.status} | ${check} | ${rule.verifiedAgainst} |`;
  });
  const counts = (s: string) => checks.filter((c) => c.rule.status === s).length;
  return [
    "# Rule pack status",
    "",
    "Generated by `npm run rules:verify`. Do not edit by hand.",
    "",
    `${checks.length} entries: ${counts("VERIFIED")} VERIFIED, ${counts("UNVERIFIED")} UNVERIFIED.`,
    "",
    "Official texts are read from the EU Publications Office CELLAR service (the same Official Journal documents EUR-Lex shows). The `url` field in each rule links to EUR-Lex for people. \"verbatim\" means every fragment of the excerpt was found word for word in the official English text after whitespace normalisation.",
    "",
    "| ID | Title | Kind | Status | Excerpt check | Verified against |",
    "|---|---|---|---|---|---|",
    ...rows,
    "",
  ].join("\n");
}

async function main() {
  const refresh = process.argv.includes("--refresh");
  const rules = loadRulePack();
  const checks: Check[] = [];
  for (const rule of rules) {
    const result = await check(rule, refresh);
    checks.push(result);
    console.log(`${result.found === false ? "FAIL" : "ok  "} ${rule.id.padEnd(22)} ${result.detail}`);
  }
  writeFileSync(path.join(process.cwd(), "docs", "RULE_PACK_STATUS.md"), statusTable(checks));
  const failures = checks.filter((c) => c.found === false && c.rule.status === "VERIFIED");
  console.log(`\n${rules.length} rules checked, ${failures.length} VERIFIED rules with a mismatch.`);
  if (failures.length > 0) process.exitCode = 1;
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err);
  process.exitCode = 1;
});
