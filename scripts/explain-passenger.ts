// npm run explain -- --scenario=A --case=4 [--out=docs/GATE1_WORKED_EXAMPLE.md]
// Prints one seeded passenger's entitlements with the full trace, as Markdown.

import { writeFileSync } from "node:fs";
import { getDb } from "../src/lib/db";
import { loadRulePack } from "../src/lib/rules/pack";
import type { TraceStep } from "../src/lib/engine";

const arg = (name: string, fallback: string) => process.argv.find((a) => a.startsWith(`--${name}=`))?.split("=")[1] ?? fallback;

async function main() {
  const scenario = arg("scenario", "A");
  const caseNo = Number(arg("case", "4"));
  const out = process.argv.find((a) => a.startsWith("--out="))?.split("=")[1];
  const rules = new Map(loadRulePack().map((r) => [r.id, r]));
  const db = getDb();
  try {
    const p = await db.passenger.findFirst({
      where: { manifestIndex: caseNo - 1, disruption: { scenarioKey: scenario, isDemoData: true, judgeRunId: null } },
      include: { entitlements: true, booking: true, disruption: { include: { flight: true } } },
    });
    if (!p) throw new Error(`No seeded passenger for scenario ${scenario} case ${caseNo}. Run npm run reset-demo first.`);
    const f = p.disruption.flight;
    const lines = [
      `# Worked example: scenario ${scenario}, quick-run case ${caseNo}`,
      "",
      "Demo data: the passenger, booking and airline are synthetic. Generated by `npm run explain` from the seeded database; the decision on extraordinary circumstances is still PENDING, so compensation shows as awaiting decision.",
      "",
      "| Field | Value |",
      "|---|---|",
      `| Passenger | ${p.displayName} (Demo data) |`,
      `| Flight | ${f.flightNumber} ${f.origin} to ${f.destination}, ${f.status.toLowerCase()} |`,
      `| Scheduled departure (UTC) | ${f.schedDep.toISOString()} |`,
      `| Passengers informed (UTC) | ${p.disruption.informedAt?.toISOString() ?? "not recorded"} |`,
      `| Booking | ${p.booking.pnr}, ${p.booking.totalCents / 100} EUR, first departure ${p.firstDeparture}, final destination ${p.finalDestination} |`,
      `| Scheduled arrival at final destination (UTC) | ${p.schedArrFinal.toISOString()} |`,
      `| Re-routing offered | ${JSON.stringify(p.rerouting)} |`,
      `| Fare type | ${p.fareType} |`,
      `| Choice | ${p.choice} |`,
      "",
      "## Entitlements",
      "",
      "| Kind | Amount | Status |",
      "|---|---|---|",
      ...p.entitlements.map((e) => `| ${e.kind} | ${(e.amountCents / 100).toFixed(2)} EUR | ${e.status} |`),
    ];
    for (const e of p.entitlements) {
      lines.push("", `## Trace: ${e.kind} (${(e.amountCents / 100).toFixed(2)} EUR, ${e.status}, engine ${e.engineVersion})`, "");
      lines.push("| # | Rule | Kind | Outcome | Inputs |", "|---|---|---|---|---|");
      (e.trace as unknown as TraceStep[]).forEach((s, i) => {
        const rule = rules.get(s.ruleId);
        lines.push(`| ${i + 1} | ${s.ruleId}: ${rule?.title ?? "UNKNOWN"} | ${rule?.kind ?? "?"} | ${s.outcome} | \`${JSON.stringify(s.inputs).replace(/\|/g, "/")}\` |`);
      });
    }
    const md = lines.join("\n") + "\n";
    if (out) {
      writeFileSync(out, md);
      console.log(`Written to ${out}`);
    } else console.log(md);
  } finally {
    await db.$disconnect();
  }
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err);
  process.exitCode = 1;
});
